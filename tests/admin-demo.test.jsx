// @vitest-environment jsdom
import React from 'react';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import { AdminWorkspace } from '../src/features/AdminWorkspace';
import { DemoAccess } from '../src/features/DemoAccess';
afterEach(() => { cleanup(); localStorage.clear(); vi.restoreAllMocks(); });
it('pausa y reactiva un chofer con confirmación conservando la membresía de ejemplo', async () => {
 const confirm = vi.spyOn(window,'confirm').mockReturnValue(false);
 render(<AdminWorkspace demo/>);
 fireEvent.click(within(screen.getByRole('navigation',{name:'Administración de plataforma'})).getByRole('button',{name:'Usuarios'}));
 fireEvent.click(await screen.findByRole('button',{name:'Pausar acceso de chofer.norte@example.com'}));
 expect(screen.getByRole('button',{name:'Pausar acceso de chofer.norte@example.com'})).toBeTruthy();
 confirm.mockReturnValue(true);
 fireEvent.click(screen.getByRole('button',{name:'Pausar acceso de chofer.norte@example.com'}));
 expect(await screen.findByText('Acceso de demostración actualizado.')).toBeTruthy();
 expect(within(screen.getByRole('button',{name:'Reactivar acceso de chofer.norte@example.com'}).closest('tr')).getByText('Inactivo')).toBeTruthy();
 expect(screen.queryByRole('button',{name:'Pausar acceso de titular.norte@example.com'})).toBeNull();
 fireEvent.click(screen.getByRole('button',{name:'Reactivar acceso de chofer.norte@example.com'}));
 expect(await screen.findByRole('button',{name:'Pausar acceso de chofer.norte@example.com'})).toBeTruthy();
 expect(JSON.parse(localStorage.getItem('hidrotrack.admin-demo.v1'))[0].members).toHaveLength(2);
});
it('filtra personas por correo, empresa, rol y acceso, y abre su empresa', async () => {
 render(<AdminWorkspace demo/>);
 fireEvent.click(within(screen.getByRole('navigation', { name: 'Administración de plataforma' })).getByRole('button', { name: 'Usuarios' }));
 await screen.findByRole('heading', { name: 'Directorio de usuarios' });
 expect(screen.getByText('4 de 4')).toBeTruthy();
 fireEvent.change(screen.getByLabelText('Rol'), { target: { value: 'driver' } });
 expect(screen.getByText('1 de 4')).toBeTruthy();
 expect(screen.getByText('chofer.norte@example.com')).toBeTruthy();
 fireEvent.change(screen.getByLabelText('Rol'), { target: { value: 'all' } });
 fireEvent.change(screen.getByLabelText('Acceso'), { target: { value: 'Bloqueado por licencia' } });
 expect(screen.getByText('titular.centro@example.com')).toBeTruthy();
 expect(screen.queryByText('chofer.norte@example.com')).toBeNull();
 fireEvent.change(screen.getByLabelText('Buscar usuarios'), { target: { value: '  CENTRAL  ' } });
 expect(screen.getByText('1 de 4')).toBeTruthy();
 fireEvent.click(screen.getByRole('button', { name: 'Ver empresa de titular.centro@example.com' }));
 expect(screen.getByRole('heading', { name: 'Soda Central' })).toBeTruthy();
 expect(screen.queryByRole('heading', { name: 'Sodería del Norte' })).toBeNull();
});

it('gestiona la suspensión en demo sin modificar otros repartos ni llamar al servidor', async () => {
 const client = { rpc: vi.fn(), from: vi.fn() };
 render(<AdminWorkspace demo client={client}/>);
 const tenant = (await screen.findByRole('heading', { name: 'Sodería del Norte' })).closest('article');
 fireEvent.click(within(tenant).getByRole('button', { name: 'Editar licencia' }));
 fireEvent.change(within(tenant).getByLabelText('Estado'), { target: { value: 'suspended' } });
 fireEvent.click(within(tenant).getByRole('button', { name: 'Guardar licencia' }));
 await screen.findByText('Licencia de demostración actualizada.');
 fireEvent.click(within(screen.getByRole('navigation', { name: 'Administración de plataforma' })).getByRole('button', { name: 'Usuarios' }));
 fireEvent.change(screen.getByLabelText('Acceso'), { target: { value: 'Habilitado' } });
 expect(screen.getByText('titular.sur@example.com')).toBeTruthy();
 expect(screen.queryByText('titular.norte@example.com')).toBeNull();
 expect(client.from).not.toHaveBeenCalled();
 expect(client.rpc).not.toHaveBeenCalled();
});
it('muestra ejemplos y crea una sodería sin consultar Supabase ni guardar contraseñas', async () => {
 const client = { rpc: vi.fn(), functions: { invoke: vi.fn() } };
 render(<AdminWorkspace demo client={client}/>);
 await screen.findByText('Sodería del Norte');
 fireEvent.click(screen.getByText('Nueva sodería'));
 fireEvent.change(screen.getByLabelText('Nombre de la sodería'), { target: { value: 'Soda Demo Nueva' } });
 fireEvent.change(screen.getByLabelText('Correo del titular'), { target: { value: 'nuevo@example.com' } });
 fireEvent.change(screen.getByLabelText('Contraseña inicial'), { target: { value: 'password-no-guardar' } });
 fireEvent.click(screen.getByText('Confirmar alta'));
 await screen.findByText('Soda Demo Nueva');
 expect(client.rpc).not.toHaveBeenCalled();
 expect(client.functions.invoke).not.toHaveBeenCalled();
 expect(localStorage.getItem('hidrotrack.admin-demo.v1')).not.toContain('password-no-guardar');
 cleanup();
 render(<AdminWorkspace demo/>);
 await screen.findByText('Soda Demo Nueva');
});
it('permite elegir perfil, valida credenciales ficticias y simula recuperar contraseña', () => {
 const onLogin = vi.fn();
 render(<DemoAccess onLogin={onLogin} onExit={() => {}}/>);
 expect(screen.getByLabelText('Perfil de demostración').value).toBe('owner');
 fireEvent.change(screen.getByLabelText('Contraseña'), { target: { value: 'incorrecta' } });
 fireEvent.click(screen.getByText('Ingresar a la demo'));
 expect(onLogin).not.toHaveBeenCalled();
 fireEvent.change(screen.getByLabelText('Perfil de demostración'), { target: { value: 'admin' } });
 fireEvent.click(screen.getByText('Ingresar a la demo'));
 expect(onLogin).toHaveBeenCalledWith('admin');
 fireEvent.click(screen.getByText('Olvidé mi contraseña'));
 fireEvent.click(screen.getByText('Simular recuperación'));
 expect(screen.getByRole('status').textContent).toContain('No se envió ningún mensaje');
});
